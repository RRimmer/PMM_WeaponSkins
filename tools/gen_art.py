#!/usr/bin/env python3
"""Generates the picture classes and the rarity table for PMM_WeaponSkins.

Input : WeaponSkins/Data/*.json (the CSGO-API dump shipped with WeaponSkins by Star).
Output: panorama/styles/custom_game/pmm_ws_art.css       skins, base weapons, agents, music kits, pins, charms
        panorama/styles/custom_game/pmm_ws_stickers.css  stickers
        pmm_ws_items.json                                 rarity per item (the WeaponSkins catalogue has none)

Every picture is one the CS2 client already has (s2r://panorama/images/econ/...), so the addon carries none.
Usage: python3 gen_art.py <WeaponSkins Data folder> <PMM_WeaponSkins project folder>
"""
import json
import os
import re
import sys

RARITY = {"common": 1, "uncommon": 2, "rare": 3, "mythical": 4, "legendary": 5, "ancient": 6, "contraband": 7, "default": 1}
HEAD = "/* Generated by tools/gen_art.py from WeaponSkins/Data. Do not edit by hand. */\n"


def rarity(item):
    rid = ((item.get("rarity") or {}).get("id") or "").lower()
    m = re.match(r"rarity_([a-z]+)", rid)
    return RARITY.get(m.group(1), 3) if m else 3


def url(path):
    return f'background-image: url("s2r://panorama/images/{path}_png.vtex");'


def load(folder, name):
    with open(os.path.join(folder, name), encoding="utf-8") as f:
        return json.load(f)


def model_key(model):
    base = model.replace("\\", "/").rsplit("/", 1)[-1]
    return base[:-5] if base.lower().endswith(".vmdl") else base


def main():
    data, project = sys.argv[1], sys.argv[2]
    styles = os.path.join(project, "panorama", "styles", "custom_game")
    os.makedirs(styles, exist_ok=True)
    art, items = [], {"sk": {}, "ag": {}, "mk": {}, "pn": {}, "st": {}, "kc": {}, "bw": []}

    # base weapons, knives and gloves
    for w in load(data, "base_weapons.json"):
        cls = w["id"].split("-", 1)[1]
        d = int(w["def_index"])
        art.append(f".bw-{d} {{ {url('econ/weapons/base_weapons/' + cls)} }}")
        items["bw"].append(d)

    # skins: weapon, knife and glove paints
    seen = set()
    for s in load(data, "skins.json"):
        paint = int(s.get("paint_index") or 0)
        weapon = s.get("weapon") or {}
        d = int(weapon.get("weapon_id") or 0)
        pattern = (s.get("pattern") or {}).get("id")
        cls = (s.get("original") or {}).get("name") or weapon.get("id") or ""
        if paint <= 0 or d <= 0 or not pattern or not cls or cls.startswith("sfui_") or (d, paint) in seen:
            continue
        seen.add((d, paint))
        art.append(f".sk-{d}-{paint} {{ {url('econ/default_generated/' + cls + '_' + pattern + '_light')} }}")
        items["sk"][f"{d}:{paint}"] = rarity(s)

    for a in load(data, "agents.json"):
        model = a.get("model_player") or ""
        image = (a.get("original") or {}).get("image_inventory")
        if not model or not image:
            continue
        key = model_key(model)
        art.append(f".ag-{key} {{ {url(image)} }}")
        items["ag"][key] = rarity(a)

    for m in load(data, "music_kits.json"):
        if m["id"].endswith("_st"):
            continue
        image = (m.get("original") or {}).get("image_inventory")
        if image:
            art.append(f".mk-{int(m['def_index'])} {{ {url(image)} }}")
            items["mk"][str(int(m["def_index"]))] = rarity(m)

    for c in load(data, "collectibles.json"):
        image = (c.get("original") or {}).get("image_inventory")
        if image:
            art.append(f".pn-{int(c['def_index'])} {{ {url(image)} }}")
            items["pn"][str(int(c["def_index"]))] = rarity(c)

    for k in load(data, "keychains.json"):
        image = (k.get("original") or {}).get("image_inventory")
        if image:
            art.append(f".kc-{int(k['def_index'])} {{ {url(image)} }}")
            items["kc"][str(int(k["def_index"]))] = rarity(k)

    stickers = []
    for s in load(data, "stickers.json"):
        image = (s.get("original") or {}).get("image_inventory")
        if image:
            stickers.append(f".st-{int(s['def_index'])} {{ {url(image)} }}")
            items["st"][str(int(s["def_index"]))] = rarity(s)

    with open(os.path.join(styles, "pmm_ws_art.css"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEAD + "\n".join(art) + "\n")
    with open(os.path.join(styles, "pmm_ws_stickers.css"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEAD + "\n".join(stickers) + "\n")
    with open(os.path.join(project, "pmm_ws_items.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(items, f, separators=(",", ":"), sort_keys=True)
    print("art", len(art), "stickers", len(stickers), {k: len(v) for k, v in items.items()})


if __name__ == "__main__":
    main()
